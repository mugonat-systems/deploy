<?php

namespace Deployer;

set('hook_node_modules', true);
set('node_install_command', 'npm ci');
set('node_build_scripts', ['build']); // string or array, run in order

desc('NPM install & build for production');
task('deploy:node_modules', function () {
    cd('{{release_or_current_path}}');

    $scripts = (array) get('node_build_scripts');

    try {
        run('{{node_install_command}}');

        foreach ($scripts as $script) {
            run('npm run ' . escapeshellarg($script));
        }
    } finally {
        run('rm -rf node_modules');
    }
});

after('deploy:vendors', function () {
    if (get('hook_node_modules')) {
        invoke('deploy:node_modules');
    }
});
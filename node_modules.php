<?php

namespace Deployer;

set('hook_node_modules', true);
set('node_build_scripts', ['build']); // string or array, run in order

// Auto-detect by default; override with set('node_install_command', '...') to force one
set('node_install_command', function () {
    $path = get('release_or_current_path');

    if (test("[ -f $path/package-lock.json ] || [ -f $path/npm-shrinkwrap.json ]")) {
        return 'npm ci';
    }
    if (test("[ -f $path/pnpm-lock.yaml ]")) {
        return 'pnpm install --frozen-lockfile';
    }
    if (test("[ -f $path/yarn.lock ]")) {
        return 'yarn install --frozen-lockfile';
    }

    warning('No lockfile found, falling back to npm install');
    return 'npm install';
});

desc('NPM install & build for production');
task('deploy:node_modules', function () {
    cd('{{release_or_current_path}}');

    $scripts = (array) get('node_build_scripts');

    try {
        run('{{node_install_command}}');

        foreach ($scripts as $script) {
            run('npm run ' . escapeshellarg($script));
        }
    } finally {
        run('rm -rf node_modules');
    }
});

after('deploy:vendors', function () {
    if (get('hook_node_modules')) {
        invoke('deploy:node_modules');
    }
});